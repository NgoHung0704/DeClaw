"""Typed request bodies for the REST surface (DCL-126, spec section 9).

Every JSON body an ``/api`` route accepts is defined here, once, so the
OpenAPI document is generated by FastAPI from these models and no route
ever parses a raw ``dict``.
"""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict

from declaw.config import Language


class SettingsUpdate(BaseModel):
    """Body of ``PUT /api/settings`` — only the three v0.1 mutable keys.

    Every field is optional; omitted fields are left untouched (an empty
    body is a no-op). Unknown keys are refused: the security toggles stay
    env-only (spec section 12), so a compromised session cannot lower the
    defenses through this schema.
    """

    model_config = ConfigDict(extra="forbid")

    model: str | None = None
    language: Language | None = None
    workspace_dir: str | None = None
