# Run from any directory. Installs development tools separately from DeClaw.
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$toolRoot = Join-Path $projectRoot '.agent-tools'
$env:UV_TOOL_DIR = Join-Path $toolRoot 'tools'
$env:UV_TOOL_BIN_DIR = Join-Path $toolRoot 'bin'
$env:UV_CACHE_DIR = Join-Path $toolRoot 'cache'
$env:UV_PYTHON_INSTALL_DIR = Join-Path $toolRoot 'python'
$env:SERENA_HOME = Join-Path $toolRoot 'serena-home'
$env:SERENA_USAGE_REPORTING = 'false'
$env:PYTHONUTF8 = '1'

& uv tool install -p 3.13 'serena-agent==2.1.0'
if ($LASTEXITCODE -ne 0) { throw 'Serena installation failed.' }

# Merge only our two MCP tables; preserve all other project settings.
$configDir = Join-Path $projectRoot '.codex'
$configPath = Join-Path $configDir 'config.toml'
$existing = if (Test-Path -LiteralPath $configPath) {
    Get-Content -LiteralPath $configPath -Raw
} else { '' }
if ($existing -match '(?m)^\[mcp_servers\.(serena|context7)(\.|\])') {
    throw 'Serena/Context7 already configured: inspect config.toml instead of overwriting.'
}
$portableRoot = $projectRoot.Replace('\', '/')
$config = @"

# Local developer tools; generated by scripts/setup-agent-tools.ps1.
[mcp_servers.serena]
command = '$portableRoot/.agent-tools/bin/serena.exe'
args = ['start-mcp-server', '--project', '$portableRoot', '--context', 'codex', '--agent-interface', 'tools', '--open-web-dashboard', 'false', '--enable-web-dashboard', 'false', '--enable-gui-log-window', 'false']
cwd = '$portableRoot'
startup_timeout_sec = 120
tool_timeout_sec = 120

[mcp_servers.serena.env]
PYTHONUTF8 = '1'
SERENA_USAGE_REPORTING = 'false'
SERENA_HOME = '$portableRoot/.agent-tools/serena-home'
UV_TOOL_DIR = '$portableRoot/.agent-tools/tools'
UV_TOOL_BIN_DIR = '$portableRoot/.agent-tools/bin'
UV_CACHE_DIR = '$portableRoot/.agent-tools/cache'
UV_PYTHON_INSTALL_DIR = '$portableRoot/.agent-tools/python'

[mcp_servers.context7]
url = 'https://mcp.context7.com/mcp'
startup_timeout_sec = 30
tool_timeout_sec = 60
"@
New-Item -ItemType Directory -Path $configDir -Force | Out-Null
[System.IO.File]::WriteAllText($configPath, $existing + $config, [System.Text.UTF8Encoding]::new($false))
Write-Output "Configured project MCP servers in $configPath. Start a new Codex session to load them."
